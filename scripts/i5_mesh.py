"""Generate the parametric inlet mesh / case (I5).

Usage:
  python -s scripts/i5_mesh.py --out cases/inlet/NAME [--level 0|1|2] [--set cr_int=1.2 ...]
                               [--mesh-set dy_wall=6e-7 ...] [--mesh-only] [--run-mesh]
                               [--mach 5 --q 50e3 --iters 3000 --np 4]
  --set       inlet parameters (geometry/inlet_param.InletParams; defaults = decisions.md D-016)
  --mesh-set  mesh parameters (geometry/inlet_mesh.MeshParams, level-0 values)
  --mesh-only write only what blockMesh/checkMesh need; --run-mesh runs them and prints the quality numbers.
Changing any single parameter and re-running regenerates the whole mesh (I5 success criterion).

Without --mesh-only a complete HiSA case is written for a smoke run (NOT an I7 result case). Its settings
are the ones approved for I4 and are reused unchanged (decisions.md D-016):
  steady HiSA numerics of examples/flatPlate (D-012), k-omega SST with D-013 A, B, C, E-1, F-1, G-1,
  characteristic far field at `inlet` and `top`, zeroGradient at both outlets (no pressure imposed, rule 6),
  symmetry plane upstream of the leading edge, isothermal no-slip walls at InletParams.T_wall.
Free stream: constant dynamic pressure q on the U.S. Standard Atmosphere 1976 (src/atmosphere.py) —
a provisional trajectory used for first-cell sizing only; the I7 trajectory is decided at I7.
"""
import argparse
import json
import re
import shutil
import subprocess
import sys
from dataclasses import asdict, fields, replace
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from geometry import inlet_mesh as im  # noqa: E402
from geometry import inlet_param as ip  # noqa: E402
from scripts import i4_cases as i4  # noqa: E402
from scripts.i3_cases import control  # noqa: E402
from src import atmosphere as atm  # noqa: E402
from src import boundary_layer as bl  # noqa: E402
from src import constants as C  # noqa: E402

FOAM = "source /usr/lib/openfoam/openfoam2512/etc/bashrc >/dev/null 2>&1"
HDR = """FoamFile
{{
    version     2.0;
    format      ascii;
    class       {cls};
    object      {obj};
}}
// generated by scripts/i5_mesh.py — do not edit by hand
"""
WALLS = '"(' + "|".join(im.WALL_PATCHES) + ')"'
MINIMAL = {"controlDict": "application hisa;\nstartFrom startTime;\nstartTime 0;\nstopAt endTime;\nendTime 1;\n"
                          "deltaT 1;\nwriteControl timeStep;\nwriteInterval 1;\n",
           "fvSchemes": "ddtSchemes { default steadyState; }\ngradSchemes { default Gauss linear; }\n"
                        "divSchemes { default none; }\nlaplacianSchemes { default Gauss linear corrected; }\n"
                        "interpolationSchemes { default linear; }\nsnGradSchemes { default corrected; }\n",
           "fvSolution": "solvers {}\n"}


def write(path, cls, obj, body):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(HDR.format(cls=cls, obj=obj) + body)


def _jsonable(o):
    if isinstance(o, dict):
        return {k: _jsonable(v) for k, v in o.items()}
    if isinstance(o, (list, tuple, np.ndarray)):
        return [_jsonable(v) for v in o]
    if isinstance(o, (np.floating, np.integer)):
        return o.item()
    return o


def git_state():
    run = lambda *a: subprocess.run(["git", "-C", str(ROOT), *a], capture_output=True, text=True).stdout.strip()  # noqa: E731
    return dict(commit=run("rev-parse", "HEAD"),
                dirty_files=len(run("status", "--porcelain", "--untracked-files=no").splitlines()))


def write_params(case, p, mp, info, extra=None):
    doc = dict(inlet_params=asdict(p), mesh_params=asdict(mp), design=ip.design(p), mesh=info, git=git_state(),
               kantrowitz_start_mach=ip.kantrowitz_start_mach(p), detachment_machs=ip.detachment_machs(p))
    doc.update(extra or {})
    (case / "params.json").write_text(json.dumps(_jsonable(doc), indent=1) + "\n")


def write_mesh_case(case, p, mp):
    """Write system/blockMeshDict (+ the minimal dictionaries checkMesh needs) and params.json."""
    case = Path(case)
    m, info = im.build(p, mp)
    if case.exists():
        shutil.rmtree(case)
    write(case / "system/blockMeshDict", "dictionary", "blockMeshDict", m.render())
    for name, body in MINIMAL.items():
        write(case / "system" / name, "dictionary", name, body)
    write_params(case, p, mp, info)
    return info


def run_mesh(case):
    """blockMesh + checkMesh in `case`; returns the quality numbers parsed from log.checkMesh."""
    case = Path(case)
    r = subprocess.run(["bash", "-c", f"{FOAM}; blockMesh > log.blockMesh 2>&1 && checkMesh > log.checkMesh 2>&1"],
                       cwd=case)
    if r.returncode != 0:
        raise RuntimeError(f"blockMesh/checkMesh failed in {case} (see log.blockMesh, log.checkMesh)")
    return parse_checkmesh((case / "log.checkMesh").read_text())


def parse_checkmesh(log):
    num = r"([-+0-9.eE]+)"
    g = lambda pat: float(re.search(pat, log).group(1))  # noqa: E731
    stars = [ln.strip() for ln in log.splitlines() if ln.lstrip().startswith("***")]
    failed = re.search(r"Failed (\d+) mesh checks", log)
    return dict(cells=int(g(r"cells:\s+(\d+)")), mesh_ok="Mesh OK." in log,
                failed_checks=int(failed.group(1)) if failed else 0, problems=stars,
                only_aspect_ratio_failed=all("aspect ratio" in s for s in stars),
                aspect_ratio_max=g(r"Max aspect ratio[:=]\s*" + num),
                non_ortho_max=g(r"non-orthogonality Max:\s*" + num), non_ortho_avg=g(r"average:\s*" + num),
                skewness_max=g(r"Max skewness =\s*" + num),
                negative_volumes="negative" in log.lower() and "Cell volumes OK" not in log)


def freestream(M, q):
    """Free-stream state on the provisional constant-q trajectory (i4_cases.freestream format + altitude)."""
    a = atm.constant_q_point(M, q)
    fs = i4.freestream(M, a["T"], rho=a["p"] / (C.R_AIR * a["T"]))
    fs.update(h=a["h"], q=a["q"], sea_level_clamped=a["sea_level_clamped"])
    return fs


def inlet_fields(fs, T_wall):
    """I4 boundary conditions (D-013 E-1 fixed-value walls, G-1 TMR inflow turbulence) mapped onto the inlet
    patch names: wall -> all wall patches, outlet -> outlet_ext and outlet_duct."""
    out = {}
    for name, (cls, body) in i4.fields(fs, T_wall, "fixed", "tmr").items():
        assert "    wall\n" in body and "    outlet\n" in body
        out[name] = (cls, body.replace("    wall\n", f"    {WALLS}\n").replace("    outlet\n", '    "outlet_.*"\n'))
    return out


def write_case(case, p, mp, M, q, iters, np_):
    """Complete HiSA smoke case. Refuses to overwrite a case that has been run (run_info.txt)."""
    case = Path(case)
    if (case / "run_info.txt").exists():
        raise SystemExit(f"{case} has already been run (run_info.txt) — not overwritten")
    info = write_mesh_case(case, p, mp)
    fs = freestream(M, q)
    ctrl = control("hisa", iters, 1, 250, False, None, ("inlet", "top", "outlet_ext", "outlet_duct"),
                   purge=4, write_by_step=True)
    write(case / "system/controlDict", "dictionary", "controlDict", ctrl)
    write(case / "system/fvSchemes", "dictionary", "fvSchemes", i4.SCHEMES["sstExample"])
    write(case / "system/fvSolution", "dictionary", "fvSolution", i4.SOLUTION)
    write(case / "system/decomposeParDict", "dictionary", "decomposeParDict", i4.DECOMPOSE.format(np=np_))
    write(case / "constant/thermophysicalProperties", "dictionary", "thermophysicalProperties", i4.thermo())
    write(case / "constant/turbulenceProperties", "dictionary", "turbulenceProperties", i4.TURB)
    for name, (cls, body) in inlet_fields(fs, p.T_wall).items():
        write(case / "0.orig" / name, cls, name, body)
    (case / "Allrun").write_text(i4.ALLRUN.format(np=np_).replace("scripts/i4_cases.py", "scripts/i5_mesh.py"))
    (case / "Allrun").chmod(0o755)
    T0 = fs["T"] * (1 + 0.5 * (C.GAMMA_AIR - 1) * M**2)
    (case / "case_info.txt").write_text(
        f"case {case.name}  (I5 smoke case — settings reused from I4: D-012, D-013 A B C E-1 F-1 G-1; D-016)\n"
        f"M {M:g}  q {fs['q']:.6g} Pa (requested {q:g}, sea-level clamp {fs['sea_level_clamped']})  "
        f"h_geopotential {fs['h']:.6g} m\n"
        f"T_inf {fs['T']:.6g} K  p_inf {fs['p']:.6g} Pa  U_inf {fs['U']:.6g} m/s  rho_inf {fs['rho']:.6g} kg/m3  "
        f"mu_inf {fs['mu']:.6g} Pa s  Re/m {fs['re_unit']:.6g}  T0 {T0:.6g} K\n"
        f"T_w {p.T_wall:g} K  T_aw(r=0.89) {bl.recovery_temperature(fs['T'], M):.6g} K\n"
        f"mesh level {mp.level}  cells {info['cells']}  dy_wall {info['dy_wall']:.4g} m  dy_lip {info['dy_lip']:.4g} m  "
        f"wall-layer ratio {info['ratio']['wall']:.4f}  lip-layer ratio {info['ratio']['lip']:.4f}\n"
        f"inlet parameters {asdict(p)}\n")
    write_params(case, p, mp, info, dict(freestream=fs, iterations=iters, np=np_))
    return info, fs


def mesh_overrides(mp, assignments):
    types = {f.name: f.type for f in fields(mp)}
    kw = {}
    for a in assignments:
        k, _, v = a.partition("=")
        if k not in types:
            raise SystemExit(f"unknown mesh parameter '{k}' (known: {', '.join(sorted(types))})")
        kw[k] = int(v) if types[k] in (int, "int") else float(v)
    return replace(mp, **kw)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--level", type=int, default=0, choices=(0, 1, 2))
    ap.add_argument("--set", nargs="*", default=[], metavar="NAME=VALUE", help="inlet parameters")
    ap.add_argument("--mesh-set", nargs="*", default=[], metavar="NAME=VALUE", help="mesh parameters")
    ap.add_argument("--mesh-only", action="store_true")
    ap.add_argument("--run-mesh", action="store_true", help="run blockMesh + checkMesh and print quality")
    ap.add_argument("--mach", type=float, default=5.0)
    ap.add_argument("--q", type=float, default=50e3, help="dynamic pressure [Pa] of the provisional trajectory")
    ap.add_argument("--iters", type=int, default=3000)
    ap.add_argument("--np", type=int, default=4, help="MPI processes (default 4, max 8 — D-009)")
    a = ap.parse_args(argv)
    if not 1 <= a.np <= 8:
        ap.error("--np must be 1..8 (CLAUDE.md)")
    try:
        p = ip.with_overrides(ip.InletParams(), a.set)
    except ValueError as e:
        ap.error(str(e))
    mp = mesh_overrides(replace(im.MeshParams(), level=a.level), a.mesh_set)
    if a.mesh_only:
        info = write_mesh_case(a.out, p, mp)
    else:
        info, fs = write_case(a.out, p, mp, a.mach, a.q, a.iters, a.np)
        print(f"free stream: M {fs['M']:g}  p {fs['p']:.5g} Pa  T {fs['T']:.5g} K  Re/m {fs['re_unit']:.4g}")
    print(f"wrote {a.out}: level {mp.level}, {info['cells']} cells, {info['blocks']} blocks, "
          f"dy_wall {info['dy_wall']:.3g} m, dy_lip {info['dy_lip']:.3g} m, max cell ratio {info['max_cell_ratio']:.3f}")
    if a.run_mesh:
        qy = run_mesh(a.out)
        print(f"checkMesh: cells {qy['cells']}, non-orthogonality max {qy['non_ortho_max']:.1f} avg "
              f"{qy['non_ortho_avg']:.1f}, skewness max {qy['skewness_max']:.2f}, aspect ratio max "
              f"{qy['aspect_ratio_max']:.0f}, failed checks {qy['failed_checks']} {qy['problems']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
