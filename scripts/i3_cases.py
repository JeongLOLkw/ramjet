"""Generate the I3 solver-validation cases (rhoCentralFoam and HiSA).

Usage:  python -s scripts/i3_cases.py            # writes cases/validation/<family>/<case>/
Cases (inviscid, calorically perfect air from src/constants.py):
  sod/        Sod shock tube, x in [-0.5, 0.5] m, N = 100..1600 (rcf), 100..800 (HiSA)
  wedge/      oblique shock, A: M 2.5 / 15 deg, B: M 5 / 10 deg, grid n = 50, 100, 200
  expansion/  Prandtl-Meyer corner, M 2.5 / 15 deg, n = 50, 100, 200
  forwardStep/ Woodward-Colella M 3 step (normalised gas), dx = 1/40, 1/80, 1/160

Numerical settings are the tutorial/example defaults (decisions.md D-010):
  rcf : Kurganov flux, vanLeer reconstruction, Euler, maxCo 0.2
        (OpenFOAM v2512 tutorials/compressible/rhoCentralFoam/shockTube, forwardStep)
  HiSA: AUSMPlusUp, wVanLeer; unsteady = dualTime CrankNicolson 0.9 (examples/shockTube,
        forwardStep); steady = bounded dualTime steadyState + local time stepping
        (examples/flatPlate, viscous terms removed).
Each case gets an Allrun that records the git commit (CLAUDE.md rule 9).
"""
