def write(path, cls, obj, body):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(HDR.format(cls=cls, obj=obj) + body)


# --------------------------------------------------------------------------- gas

def thermo(normalised=False):
    """thermophysicalProperties from src/constants.py.

    normalised=True: Woodward-Colella units (a = 1 at T = 1): R = 1/gamma, so
    molWeight = RR * gamma, Cp = gamma/(gamma-1) * R.
    """
    g = C.GAMMA_AIR
    if normalised:
        mw = C.RR_OPENFOAM * g
        cp = g / (g - 1) * (C.RR_OPENFOAM / mw)
    else:
        mw, cp = C.MOLWEIGHT_AIR, C.CP_AIR
    return f"""thermoType
{{
    type            hePsiThermo;
    mixture         pureMixture;
    transport       const;
    thermo          hConst;
    equationOfState perfectGas;
    specie          specie;
    energy          sensibleInternalEnergy;
}}
mixture
{{
    specie         {{ nMoles 1; molWeight {mw:.10g}; }}
    thermodynamics {{ Cp {cp:.10g}; Hf 0; }}
    transport      {{ mu 0; Pr 1; }}     // inviscid
}}
"""


TURB = "simulationType laminar;\n"

# --------------------------------------------------------------------------- mesh


def block_mesh(verts2d, blocks, patches, z=0.05):
    """verts2d: list of (x, y); blocks: list of (i0, i1, i2, i3, nx, ny);
    patches: dict name -> (type, list of (a, b) 2D edges)."""
    n = len(verts2d)
    vs = [f"    ({x:.12g} {y:.12g} {-z})" for x, y in verts2d] + \
         [f"    ({x:.12g} {y:.12g} {z})" for x, y in verts2d]
    bl = [f"    hex ({a} {b} {c} {d} {a+n} {b+n} {c+n} {d+n}) ({nx} {ny} 1) simpleGrading (1 1 1)"
          for a, b, c, d, nx, ny in blocks]
    pt = []
    for name, (typ, edges) in patches.items():
        faces = " ".join(f"({a} {b} {b+n} {a+n})" for a, b in edges)
        pt.append(f"    {name} {{ type {typ}; faces ({faces}); }}")
    return ("convertToMeters 1;\nvertices\n(\n" + "\n".join(vs) + "\n);\nblocks\n(\n" + "\n".join(bl)
            + "\n);\nedges ();\nboundary\n(\n" + "\n".join(pt)
            + "\n    frontAndBack { type empty; faces ("
            + " ".join(f"({a} {d} {c} {b})" for a, b, c, d, *_ in blocks) + " "
            + " ".join(f"({a+n} {b+n} {c+n} {d+n})" for a, b, c, d, *_ in blocks)
            + "); }\n);\nmergePatchPairs ();\n")


def mesh_wedge(n, theta, L=1.0, H=1.0, x0=-0.25):
    yL = L * np.tan(theta)
    v = [(x0, 0), (0, 0), (0, H), (x0, H), (L, yL), (L, H)]
    blocks = [(0, 1, 2, 3, max(2, round(n * -x0)), n), (1, 4, 5, 2, round(n * L), n)]
    patches = {"inlet": ("patch", [(3, 0)]), "outlet": ("patch", [(4, 5)]),
               "top": ("symmetryPlane", [(2, 3), (5, 2)]), "wall": ("wall", [(0, 1), (1, 4)])}
    return block_mesh(v, blocks, patches)


def mesh_expansion(n, theta, L=1.2, H=1.0, x0=-0.5):
    yL = -L * np.tan(theta)
    v = [(x0, 0), (0, 0), (0, H), (x0, H), (L, yL), (L, H)]
    blocks = [(0, 1, 2, 3, round(n * -x0), n), (1, 4, 5, 2, round(n * L), n)]
    patches = {"inlet": ("patch", [(3, 0)]), "outlet": ("patch", [(4, 5)]),
               "top": ("symmetryPlane", [(2, 3), (5, 2)]), "wall": ("wall", [(0, 1), (1, 4)])}
    return block_mesh(v, blocks, patches)


def mesh_sod(N):
    """1D strip: the two y-faces form an extra empty patch `sides`."""
    v = [(-0.5, -0.005), (0.5, -0.005), (0.5, 0.005), (-0.5, 0.005)]
    return block_mesh(v, [(0, 1, 2, 3, N, 1)], {"left": ("patch", [(3, 0)]), "right": ("patch", [(1, 2)]),
                                               "sides": ("empty", [(0, 1), (2, 3)])})


def mesh_forward_step(f):
    """Woodward & Colella (1984) step, same vertices as the OpenFOAM tutorial; dx = 1/(80 f)."""
    v = [(0, 0), (0.6, 0), (0, 0.2), (0.6, 0.2), (3, 0.2), (0, 1), (0.6, 1), (3, 1)]
    k = lambda m: int(round(m * f))
    blocks = [(0, 1, 3, 2, k(48), k(16)), (2, 3, 6, 5, k(48), k(64)), (3, 4, 7, 6, k(192), k(64))]
    patches = {"inlet": ("patch", [(2, 0), (5, 2)]), "outlet": ("patch", [(4, 7)]),
               "bottom": ("symmetryPlane", [(0, 1)]), "top": ("symmetryPlane", [(6, 5), (7, 6)]),
               "obstacle": ("wall", [(1, 3), (3, 4)])}
    return block_mesh(v, blocks, patches)


# --------------------------------------------------------------------------- fields


def bc_block(entries):
    return "boundaryField\n{\n" + "".join(f"    {k} {{ {v} }}\n" for k, v in entries.items()) \
        + "    frontAndBack { type empty; }\n}\n"


def fields_external(solver, p, T, U, wall="wall", sym=("top",)):
    """Supersonic inflow / outflow, inviscid wall (slip). Outlet: no pressure imposed (rule 6)."""
    Uv = f"({U:.12g} 0 0)"
    pb = {"inlet": f"type fixedValue; value uniform {p:.12g};", "outlet": "type zeroGradient;"}
    Tb = {"inlet": f"type fixedValue; value uniform {T:.12g};",
          "outlet": f"type inletOutlet; inletValue uniform {T:.12g}; value uniform {T:.12g};"}
    Ub = {"inlet": f"type fixedValue; value uniform {Uv};",
          "outlet": f"type inletOutlet; inletValue uniform {Uv}; value uniform {Uv};",
          wall: "type slip;"}
    if solver == "rcf":
        pb[wall] = "type zeroGradient;"
        Tb[wall] = "type zeroGradient;"
    else:  # HiSA inviscid wall, as in examples/forwardStep
        pb[wall] = "type characteristicWallPressure; value $internalField;"
        Tb[wall] = "type characteristicWallTemperature; value $internalField;"
    for s in sym:
        for d in (pb, Tb, Ub):
            d[s] = "type symmetryPlane;"
    return {
        "p": ("volScalarField", f"dimensions [1 -1 -2 0 0 0 0];\ninternalField uniform {p:.12g};\n" + bc_block(pb)),
        "T": ("volScalarField", f"dimensions [0 0 0 1 0 0 0];\ninternalField uniform {T:.12g};\n" + bc_block(Tb)),
        "U": ("volVectorField", f"dimensions [0 1 -1 0 0 0 0];\ninternalField uniform {Uv};\n" + bc_block(Ub)),
    }


def fields_sod():
    zg = {"left": "type zeroGradient;", "right": "type zeroGradient;", "sides": "type empty;"}
    return {
        "p": ("volScalarField", "dimensions [1 -1 -2 0 0 0 0];\ninternalField uniform 1e5;\n" + bc_block(zg)),
        "T": ("volScalarField", "dimensions [0 0 0 1 0 0 0];\ninternalField uniform 300;\n" + bc_block(zg)),
        "U": ("volVectorField", "dimensions [0 1 -1 0 0 0 0];\ninternalField uniform (0 0 0);\n" + bc_block(zg)),
    }


# Sod (Toro 2009 Test 1) in SI: rho_L = 1 kg/m3, p_L = 1e5 Pa; rho_R = 0.125, p_R = 1e4.
SOD_L = (1.0, 0.0, 1e5)
SOD_R = (0.125, 0.0, 1e4)
# non-dimensional t = 0.2 with velocity scale sqrt(p_L/rho_L) and length 1 m
SOD_T = 0.2 / np.sqrt(SOD_L[2] / SOD_L[0])


def sod_setfields():
    TL = SOD_L[2] / (C.R_AIR * SOD_L[0])
    TR = SOD_R[2] / (C.R_AIR * SOD_R[0])
    return f"""defaultFieldValues
(
    volVectorFieldValue U (0 0 0)
    volScalarFieldValue T {TL:.12g}
    volScalarFieldValue p {SOD_L[2]:.12g}
);
regions
(
    boxToCell
    {{
        box (0 -1 -1) (1 1 1);
        fieldValues ( volScalarFieldValue T {TR:.12g} volScalarFieldValue p {SOD_R[2]:.12g} );
    }}
);
"""


# --------------------------------------------------------------------------- system

def mass_flux_fo(patches):
    return "".join(f"""    mf_{p}
    {{
        type surfaceFieldValue; libs (fieldFunctionObjects);
        writeControl timeStep; writeInterval 10; log false; writeFields false;
        regionType patch; name {p}; operation sum; fields (phi);
    }}
""" for p in patches)


def control(app, end, dt, write, adjust, maxCo=None, fo_patches=(), purge=0, write_by_step=False):
    wc = "timeStep" if write_by_step else "adjustableRunTime"
    s = f"""application     {app};
startFrom       latestTime;
startTime       0;
stopAt          endTime;
endTime         {end:.10g};
deltaT          {dt:.10g};
writeControl    {wc};
writeInterval   {write:.10g};
purgeWrite      {purge};
writeFormat     ascii;
writePrecision  10;
writeCompression off;
timeFormat      general;
timePrecision   10;
runTimeModifiable false;
adjustTimeStep  {"yes" if adjust else "no"};
"""
    if maxCo is not None:
        s += f"maxCo           {maxCo};\nmaxDeltaT       1;\n"
    if fo_patches:
        s += "functions\n{\n" + mass_flux_fo(fo_patches) + "}\n"
    return s


