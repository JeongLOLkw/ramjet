def freestream(M, T, re_unit=None, rho=None):
    """Free-stream state from M, T and either the unit Reynolds number [1/m] or the density."""
    U = M * np.sqrt(G * C.R_AIR * T)
    mu = float(bl.mu_sutherland(T))
    if rho is None:
        rho = re_unit * mu / U
    return dict(M=M, T=T, U=U, rho=rho, p=rho * C.R_AIR * T, mu=mu, re_unit=rho * U / mu)


