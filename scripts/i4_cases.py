def bc_block(entries):
    return "boundaryField\n{\n" + "".join(f"    {k}\n    {{\n        {v}\n    }}\n" for k, v in entries.items()) \
        + "    frontAndBack { type empty; }\n}\n"


def fields(fs, T_w, wall_bc, inflow_turb):
    p, T, U = fs["p"], fs["T"], fs["U"]
    Uv = f"({U:.10g} 0 0)"
    ff = f"U {Uv}; p {p:.10g}; T {T:.10g};"
    sym = "type symmetryPlane;"
    tu = TU[inflow_turb](fs["M"])
    k = 1.5 * (tu * U) ** 2
    if inflow_turb == "tmr":
        omega = fs["rho"] * k / (0.009 * fs["mu"])
    else:  # HiSA examples/basicFinner: omega = sqrt(k)/(Cmu^0.25 L), L = 1e-5 m
        omega = np.sqrt(k) / (0.09**0.25 * 1e-5)
    io = lambda v: f"type inletOutlet; inletValue uniform {v:.10g}; value uniform {v:.10g};"  # noqa: E731
    calc = "type calculated; value uniform 0;"
    if wall_bc == "fixed":       # D-013 E option 1: no wall-function patch types at all
        kw, ow = "type fixedValue; value uniform 0;", OMEGA_WALL_FIXED
        nw = "type fixedValue; value uniform 0;"
    elif wall_bc == "lowRe":     # D-013 E option 2: HiSA SST examples (basicFinner)
        kw, ow = "type kLowReWallFunction; value uniform 1e-11;", "type omegaWallFunction; value uniform 1e8;"
        nw = "type boundaryCorrectedNutLowReWallFunction; value uniform 0;"
    else:
        raise ValueError(wall_bc)
    pb = {"inlet": f"type characteristicFarfieldPressure; {ff} value uniform {p:.10g};",
          "top": f"type characteristicFarfieldPressure; {ff} value uniform {p:.10g};",
          "outlet": "type zeroGradient;", "sym": sym,
          "wall": f"type characteristicWallPressure; value uniform {p:.10g};"}
    Tb = {"inlet": f"type characteristicFarfieldTemperature; {ff} value uniform {T:.10g};",
          "top": f"type characteristicFarfieldTemperature; {ff} value uniform {T:.10g};",
          "outlet": "type zeroGradient;", "sym": sym,
          "wall": f"type fixedValue; value uniform {T_w:.10g};"}          # isothermal
    Ub = {"inlet": f"type characteristicFarfieldVelocity; {ff} value uniform {Uv};",
          "top": f"type characteristicFarfieldVelocity; {ff} value uniform {Uv};",
          "outlet": "type zeroGradient;", "sym": sym, "wall": "type fixedValue; value uniform (0 0 0);"}
    kb = {"inlet": io(k), "top": io(k), "outlet": "type zeroGradient;", "sym": sym, "wall": kw}
    ob = {"inlet": io(omega), "top": io(omega), "outlet": "type zeroGradient;", "sym": sym, "wall": ow}
    nb = {"inlet": calc, "top": calc, "outlet": calc, "sym": sym, "wall": nw}
    ab = {"inlet": calc, "top": calc, "outlet": calc, "sym": sym, "wall": "type fixedValue; value uniform 0;"}
    S, V = "volScalarField", "volVectorField"
    return {
        "p": (S, f"dimensions [1 -1 -2 0 0 0 0];\ninternalField uniform {p:.10g};\n" + bc_block(pb)),
        "T": (S, f"dimensions [0 0 0 1 0 0 0];\ninternalField uniform {T:.10g};\n" + bc_block(Tb)),
        "U": (V, f"dimensions [0 1 -1 0 0 0 0];\ninternalField uniform {Uv};\n" + bc_block(Ub)),
        "k": (S, f"dimensions [0 2 -2 0 0 0 0];\ninternalField uniform {k:.10g};\n" + bc_block(kb)),
        "omega": (S, f"dimensions [0 0 -1 0 0 0 0];\ninternalField uniform {omega:.10g};\n" + bc_block(ob)),
        "nut": (S, "dimensions [0 2 -1 0 0 0 0];\ninternalField uniform 0;\n" + bc_block(nb)),
        "alphat": (S, "dimensions [1 -1 -1 0 0 0 0];\ninternalField uniform 0;\n" + bc_block(ab)),
    }


