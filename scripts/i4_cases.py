def geometric_ratio(first, length, n):
    """Cell-to-cell ratio r of n geometrically graded cells of given first size filling `length`."""
    if abs(first * n - length) < 1e-12 * length:
        return 1.0
    f = lambda r: first * (r**n - 1) / (r - 1) - length  # noqa: E731
    if first * n < length:   # expanding: r^(n-1) * first < length bounds r from above
        return brentq(f, 1 + 1e-9, (length / first) ** (1.0 / (n - 1)))
    return brentq(f, 1e-3, 1 - 1e-9)


def grading(first, length, n):
    """blockMesh expansion ratio (last/first cell size) and the last cell size."""
    r = geometric_ratio(first, length, n)
    return r ** (n - 1), first * r ** (n - 1)


def block_mesh(verts2d, blocks, patches, z=0.005):
    """verts2d: [(x, y)]; blocks: [(i0, i1, i2, i3, nx, ny, gx, gy)]; patches: {name: (type, [(a, b)])}."""
    n = len(verts2d)
    vs = [f"    ({x:.12g} {y:.12g} {-z})" for x, y in verts2d] + [f"    ({x:.12g} {y:.12g} {z})" for x, y in verts2d]
    bl_ = [f"    hex ({a} {b} {c} {d} {a+n} {b+n} {c+n} {d+n}) ({nx} {ny} 1) simpleGrading ({gx:.10g} {gy:.10g} 1)"
           for a, b, c, d, nx, ny, gx, gy in blocks]
    pt = []
    for name, (typ, edges) in patches.items():
        faces = " ".join(f"({a} {b} {b+n} {a+n})" for a, b in edges)
        pt.append(f"    {name} {{ type {typ}; faces ({faces}); }}")
    return ("convertToMeters 1;\nvertices\n(\n" + "\n".join(vs) + "\n);\nblocks\n(\n" + "\n".join(bl_)
            + "\n);\nedges ();\nboundary\n(\n" + "\n".join(pt)
            + "\n    frontAndBack { type empty; faces ("
            + " ".join(f"({a} {d} {c} {b})" for a, b, c, d, *_ in blocks) + " "
            + " ".join(f"({a+n} {b+n} {c+n} {d+n})" for a, b, c, d, *_ in blocks)
            + "); }\n);\nmergePatchPairs ();\n")


def mesh_flatplate(c, f):
    """Leading edge at x = 0; symmetry section L/6 upstream. Returns (blockMeshDict, info)."""
    L, H, xu = c["L"], c["H"], -c["L"] / 6
    nxp, nxu, ny = round(208 * f), round(48 * f), round(224 * f)
    dx0, dy1 = 2e-3 / f, c["dy1"] / (2 * f)
    gxp, dx_end = grading(dx0, L, nxp)
    gxu, _ = grading(dx0, -xu, nxu)
    gy, dy_top = grading(dy1, H, ny)
    v = [(xu, 0), (0, 0), (L, 0), (xu, H), (0, H), (L, H)]
    blocks = [(0, 1, 4, 3, nxu, ny, 1 / gxu, gy), (1, 2, 5, 4, nxp, ny, gxp, gy)]
    patches = {"inlet": ("patch", [(3, 0)]), "outlet": ("patch", [(2, 5)]), "top": ("patch", [(4, 3), (5, 4)]),
               "sym": ("symmetryPlane", [(0, 1)]), "wall": ("wall", [(1, 2)])}
    info = dict(cells=(nxp + nxu) * ny, nx=nxp + nxu, ny=ny, dy1=dy1, dx_le=dx0, dx_end=dx_end, dy_top=dy_top,
                r_y=geometric_ratio(dy1, H, ny))
    return block_mesh(v, blocks, patches), info


def mesh_ramp(c, f):
    """Corner at the origin. Blocks: A symmetry section, B1/B2 plate (expanding / contracting in x),
    C corner approach (grid lines tilt 0 -> theta/2), D ramp (theta/2 -> wall-normal)."""
    th, H = c["theta"], c["H"]
    xle, xc = -c["L_plate"], -c["L_c"]
    dxc = 0.5e-3 / f                     # streamwise spacing on the ramp and at the corner
    dxc_up = 1.5e-3 / f                  # at the upstream end of block C
    dx0 = 2e-3 / f                       # at the leading edge
    ny = round(224 * f)
    dy1 = c["dy1"] / (2 * f)
    n_d = round(c["L_ramp"] / dxc)
    n_c = round(c["L_c"] / (0.5 * (dxc + dxc_up)))
    n_a = round(16 * f)
    n_b1, n_b2 = round(160 * f), round(160 * f)
    # split point of the plate so that the two halves end with the same cell size
    Lb = xc - xle
    xm = brentq(lambda s: grading(dx0, s, n_b1)[1] - grading(dxc_up, Lb - s, n_b2)[1], 0.05 * Lb, 0.95 * Lb)
    gy, _ = grading(dy1, H, ny)
    hb, rn = th / 2, th
    v = [(xle - c["L_up"], 0), (xle, 0), (xle + xm, 0), (xc, 0), (0, 0),
         (c["L_ramp"] * np.cos(th), c["L_ramp"] * np.sin(th)),
         (xle - c["L_up"], H), (xle, H), (xle + xm, H), (xc, H), (-H * np.tan(hb), H),
         (c["L_ramp"] * np.cos(th) - H * np.sin(rn), c["L_ramp"] * np.sin(th) + H * np.cos(rn))]
    blocks = [(0, 1, 7, 6, n_a, ny, 1 / grading(dx0, c["L_up"], n_a)[0], gy),
              (1, 2, 8, 7, n_b1, ny, grading(dx0, xm, n_b1)[0], gy),
              (2, 3, 9, 8, n_b2, ny, 1 / grading(dxc_up, Lb - xm, n_b2)[0], gy),
              (3, 4, 10, 9, n_c, ny, 1 / grading(dxc, c["L_c"], n_c)[0], gy),
              (4, 5, 11, 10, n_d, ny, 1.0, gy)]
    patches = {"inlet": ("patch", [(6, 0)]), "outlet": ("patch", [(5, 11)]),
               "top": ("patch", [(7, 6), (8, 7), (9, 8), (10, 9), (11, 10)]),
               "sym": ("symmetryPlane", [(0, 1)]), "wall": ("wall", [(1, 2), (2, 3), (3, 4), (4, 5)])}
    nx = n_a + n_b1 + n_b2 + n_c + n_d
    info = dict(cells=nx * ny, nx=nx, ny=ny, dy1=dy1, dx_corner=dxc, dx_mid=grading(dx0, xm, n_b1)[1],
                r_y=geometric_ratio(dy1, H, ny))
    return block_mesh(v, blocks, patches), info


